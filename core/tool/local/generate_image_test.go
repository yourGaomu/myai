type imageGeneratorStub struct {
	result  imageport.GenerateResult
	request imageport.GenerateRequest
	calls   int
}

func (g *imageGeneratorStub) Generate(_ context.Context, request imageport.GenerateRequest) (imageport.GenerateResult, error) {
	g.calls++
	g.request = request
	return g.result, nil
}
func (*imageGeneratorStub) SupportsReferenceImages() bool { return true }

type imageRegistryStub struct {
	config    domain.Config
	generator imageport.Generator
}

func (r imageRegistryStub) Get(id string) (domain.Config, imageport.Generator, bool) {
	return r.config, r.generator, id == r.config.ID && r.config.Enabled
}
func (r imageRegistryStub) List() []domain.Config { return []domain.Config{r.config} }
func (r imageRegistryStub) Default() (domain.Config, imageport.Generator, bool) {
	return r.config, r.generator, r.config.Enabled && r.config.IsDefault
}
func testPNG(t *testing.T, c color.NRGBA) []byte {
	t.Helper()
	img := image.NewNRGBA(image.Rect(0, 0, 8, 6))
	for y := 0; y < 6; y++ {
		for x := 0; x < 8; x++ {
			img.SetNRGBA(x, y, c)
		}
	}
	var output bytes.Buffer
	if err := png.Encode(&output, img); err != nil {
		t.Fatal(err)
	}
	return output.Bytes()
}

type generateHistoryStub struct {
	before   *domainhistory.FileSnapshot
	recorded bool
}

func (h *generateHistoryStub) SnapshotPath(path string) (*domainhistory.FileSnapshot, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	return &domainhistory.FileSnapshot{Path: filepath.Base(path), Content: data, Size: int64(len(data)), Available: true}, nil
}
func (h *generateHistoryStub) RecordFileChange(_ context.Context, _ string, before *domainhistory.FileSnapshot, _ history.RecordCommand) (string, error) {
	h.before = before
	h.recorded = true
	return "checkpoint", nil
}

func TestGenerateImageSavesLocalAssetAndPassesVerifiedReference(t *testing.T) {
	workspace := t.TempDir()
	reference := testPNG(t, color.NRGBA{R: 20, G: 40, B: 60, A: 255})
	generated := testPNG(t, color.NRGBA{R: 220, G: 30, B: 40, A: 255})
	localPath := ".myai/generated/source.png"
	if err := os.MkdirAll(filepath.Join(workspace, filepath.Dir(localPath)), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(workspace, filepath.FromSlash(localPath)), reference, 0o600); err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(reference)
	asset := filesport.Asset{AssetID: "ast_local_source", FileName: "source.png", ContentType: "image/png", Size: int64(len(reference)), Checksum: hex.EncodeToString(sum[:])}.WithLocalImage(localPath, workspace)
	generator := &imageGeneratorStub{result: imageport.GenerateResult{Data: generated, MIMEType: "image/png"}}
	registry := imageRegistryStub{config: domain.Config{ID: "default", Name: "Default", Protocol: domain.ProtocolOpenAIImages, Enabled: true, IsDefault: true}, generator: generator}
	tool := NewGenerateImageTool(workspace, registry, nil, func(_ context.Context, sessionID, assetID string) (filesport.Asset, error) {
		if sessionID != "session-a" || assetID != asset.AssetID {
			return filesport.Asset{}, filesport.ErrSessionAssetUnavailable
		}
		return asset, nil
	}, nil)
	arguments, _ := json.Marshal(generateImageArgs{Prompt: "edit this image", ReferenceImages: []string{"asset:ast_local_source"}, OutputPath: "results/output.png"})
	ctx := toolruntime.WithExecution(context.Background(), toolruntime.Execution{SessionID: "session-a", WorkspaceRoot: workspace})
	output, err := tool.Call(ctx, arguments)
	if err != nil {
		t.Fatal(err)
	}
	if output.SharedAsset == nil {
		t.Fatal("missing generated shared asset")
	}
	if output.SharedAsset.AssetID[:len("ast_local_")] != "ast_local_" || output.SharedAsset.LocalPath != "results/output.png" || output.SharedAsset.ContentType != "image/png" {
		t.Fatalf("bad local asset: %+v", output.SharedAsset)
	}
	if generator.calls != 1 || len(generator.request.ReferenceImages) != 1 || !bytes.Equal(generator.request.ReferenceImages[0].Data, reference) {
		t.Fatal("verified reference image was not forwarded")
	}
	persisted, err := os.ReadFile(filepath.Join(workspace, "results", "output.png"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(persisted, generated) {
		t.Fatal("generated bytes were not saved")
	}
	var receipt generateImageResult
	if err := json.Unmarshal([]byte(output.Content), &receipt); err != nil {
		t.Fatal(err)
	}
	if receipt.MarkdownEmbed != "![Generated image](asset:"+receipt.AssetID+")" {
		t.Fatalf("bad markdown embed %q", receipt.MarkdownEmbed)
	}
}

func TestGenerateImageRejectsCrossSessionReferenceBeforeGeneration(t *testing.T) {
	workspace := t.TempDir()
	generator := &imageGeneratorStub{}
	registry := imageRegistryStub{config: domain.Config{ID: "default", Enabled: true, IsDefault: true}, generator: generator}
	tool := NewGenerateImageTool(workspace, registry, nil, func(context.Context, string, string) (filesport.Asset, error) {
		return filesport.Asset{}, errors.New("forbidden")
	}, nil)
	arguments := json.RawMessage(`{"prompt":"edit","reference_images":["ast_other"]}`)
	ctx := toolruntime.WithExecution(context.Background(), toolruntime.Execution{SessionID: "session-a", WorkspaceRoot: workspace})
	if _, err := tool.Call(ctx, arguments); err == nil {
		t.Fatal("cross-session reference was accepted")
	}
	if generator.calls != 0 {
		t.Fatal("provider was called before reference authorization")
	}
}

func TestGenerateImageRejectsProtectedWorkspaceReference(t *testing.T) {
	workspace := t.TempDir()
	if err := os.WriteFile(filepath.Join(workspace, ".env"), []byte("IMAGE_API_KEY=secret"), 0o600); err != nil {
		t.Fatal(err)
	}
	generator := &imageGeneratorStub{}
	registry := imageRegistryStub{config: domain.Config{ID: "default", Enabled: true, IsDefault: true}, generator: generator}
	tool := NewGenerateImageTool(workspace, registry, nil, nil, nil)
	args := json.RawMessage(`{"prompt":"edit","reference_images":[".env"]}`)
	ctx := toolruntime.WithExecution(context.Background(), toolruntime.Execution{SessionID: "session-a", WorkspaceRoot: workspace})
	if _, err := tool.Call(ctx, args); err == nil {
		t.Fatal("protected .env reference was accepted")
	}
	if generator.calls != 0 {
		t.Fatal("provider was called before protected path rejection")
	}
}

func TestGenerateImageOverwritesOnlyRegularWorkspaceFile(t *testing.T) {
	workspace := t.TempDir()
	generated := testPNG(t, color.NRGBA{R: 200, G: 40, B: 10, A: 255})
	existing := testPNG(t, color.NRGBA{R: 10, G: 20, B: 30, A: 255})
	if err := os.MkdirAll(filepath.Join(workspace, "results"), 0o700); err != nil {
		t.Fatal(err)
	}
	target := filepath.Join(workspace, "results", "existing.png")
	if err := os.WriteFile(target, existing, 0o600); err != nil {
		t.Fatal(err)
	}
	generator := &imageGeneratorStub{result: imageport.GenerateResult{Data: generated, MIMEType: "image/png"}}
	registry := imageRegistryStub{config: domain.Config{ID: "default", Enabled: true, IsDefault: true}, generator: generator}
	tool := NewGenerateImageTool(workspace, registry, nil, nil, nil)
	recorder := &generateHistoryStub{}
	tool.recorder = recorder
	args := json.RawMessage(`{"prompt":"new image","output_path":"results/existing.png"}`)
	ctx := toolruntime.WithExecution(context.Background(), toolruntime.Execution{SessionID: "session-a", WorkspaceRoot: workspace})
	if _, err := tool.Call(ctx, args); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(target)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, generated) {
		t.Fatal("existing file was not replaced")
	}
	if !recorder.recorded || recorder.before == nil || !bytes.Equal(recorder.before.Content, existing) {
		t.Fatal("pre-overwrite snapshot was not recorded")
	}
}
